import { randomUUID } from "node:crypto";
import { constants } from "node:fs";
import { access, chmod, mkdir, readFile, rename, rm, stat, writeFile } from "node:fs/promises";
import { join, posix, win32 } from "node:path";
import type { Logger } from "@zcode/contracts";

/**
 * 桌面 agent 跑在 Electron Node 上时，stdio MCP 的 `node` / `npm` / `npx` 在用户机器没装 Node 时
 * 回退到同一个 Electron 可执行文件与随包 npm。规格见 docs/design/v2/mcp-node-fallback.md。
 *
 * shim 内容是静态的，机器路径全部经由下面两个环境变量传入：AppImage 每次启动挂载点都不同，
 * 若把路径写进文件，每次启动都会产生新目录，且多个 app 版本会互相覆盖同一份 shim。
 */
export const NODE_FALLBACK_EXEC_PATH_ENV_KEY = "ZCODE_NODE_FALLBACK_EXEC_PATH";
export const NODE_FALLBACK_NPM_ROOT_ENV_KEY = "ZCODE_NODE_FALLBACK_NPM_ROOT";
const NODE_FALLBACK_DIRECTORY_NAME = "node-fallback";
/** shim 布局版本：shim 内容变化必须升级，保证正在执行的 shim 不会被改写成新内容。 */
const NODE_FALLBACK_SHIM_LAYOUT = "v1";
const NPM_CLI_ENTRY = "npm-cli.js";
const NPX_CLI_ENTRY = "npx-cli.js";
const SHIM_EXECUTABLE_MODE = 0o755;
const EXECUTABLE_BITS = 0o111;
const MISSING_ENV_EXIT_CODE = 127;
const PATH_ENV_KEY = "PATH";

export interface McpNodeFallback {
  /** 追加到 stdio MCP 子进程 PATH 末尾的 shim 目录。 */
  binDir: string;
  /** shim 需要的环境变量（Electron 可执行文件与可选的随包 npm 根目录）。 */
  env: Record<string, string>;
}

export interface McpNodeFallbackProvider {
  /** 首次调用时准备 shim 目录；结果（含失败）在 provider 生命周期内复用。失败时返回 undefined。 */
  resolve(): Promise<McpNodeFallback | undefined>;
}

export interface CreateMcpNodeFallbackProviderOptions {
  /** Electron 可执行文件（agent 的 process.execPath）。 */
  execPath: string;
  logger?: Logger;
  /** 随包 npm 根目录候选，按顺序取第一个完整的。 */
  npmRootCandidates: readonly string[];
  platform?: NodeJS.Platform;
  /** shim 目录落在 `<storageRoot>/node-fallback/<layout>`。 */
  storageRoot: string;
}

export interface NodeFallbackShimFile {
  content: string;
  executable: boolean;
  name: string;
}

interface ShimTarget {
  /** 相对 npm 根目录的 JS 入口；node shim 没有。 */
  npmEntry?: string;
  command: string;
}

const SHIM_TARGETS: readonly ShimTarget[] = [
  { command: "node" },
  { command: "npm", npmEntry: NPM_CLI_ENTRY },
  { command: "npx", npmEntry: NPX_CLI_ENTRY },
];

export function renderNodeFallbackShims(platform: NodeJS.Platform): NodeFallbackShimFile[] {
  return SHIM_TARGETS.map((target) =>
    platform === "win32"
      ? { content: renderWindowsShim(target), executable: false, name: `${target.command}.cmd` }
      : { content: renderPosixShim(target), executable: true, name: target.command },
  );
}

function renderPosixShim(target: ShimTarget): string {
  const lines = [
    "#!/bin/sh",
    `# Generated by ZCode: ${target.command} fallback on the Electron Node runtime.`,
    ...renderPosixEnvGuard(NODE_FALLBACK_EXEC_PATH_ENV_KEY),
    ...(target.npmEntry ? renderPosixEnvGuard(NODE_FALLBACK_NPM_ROOT_ENV_KEY) : []),
    "ELECTRON_RUN_AS_NODE=1",
    "export ELECTRON_RUN_AS_NODE",
  ];
  if (target.npmEntry) {
    // 随包 npm 不是用户的全局 npm，不能提示用户去升级它；用户显式设置时保持原值。
    lines.push(
      ': "${npm_config_update_notifier:=false}"',
      "export npm_config_update_notifier",
      `exec "$${NODE_FALLBACK_EXEC_PATH_ENV_KEY}" "$${NODE_FALLBACK_NPM_ROOT_ENV_KEY}/bin/${target.npmEntry}" "$@"`,
    );
  } else {
    lines.push(`exec "$${NODE_FALLBACK_EXEC_PATH_ENV_KEY}" "$@"`);
  }
  return `${lines.join("\n")}\n`;
}

function renderPosixEnvGuard(envKey: string): string[] {
  return [
    `if [ -z "\${${envKey}:-}" ]; then`,
    `  echo "zcode node fallback: ${envKey} is not set" >&2`,
    `  exit ${MISSING_ENV_EXIT_CODE}`,
    "fi",
  ];
}

function renderWindowsShim(target: ShimTarget): string {
  const lines = [
    "@echo off",
    `rem Generated by ZCode: ${target.command} fallback on the Electron Node runtime.`,
    ...renderWindowsEnvGuard(NODE_FALLBACK_EXEC_PATH_ENV_KEY),
    ...(target.npmEntry ? renderWindowsEnvGuard(NODE_FALLBACK_NPM_ROOT_ENV_KEY) : []),
    "setlocal",
    'set "ELECTRON_RUN_AS_NODE=1"',
  ];
  if (target.npmEntry) {
    lines.push(
      'if not defined npm_config_update_notifier set "npm_config_update_notifier=false"',
      `"%${NODE_FALLBACK_EXEC_PATH_ENV_KEY}%" "%${NODE_FALLBACK_NPM_ROOT_ENV_KEY}%\\bin\\${target.npmEntry}" %*`,
    );
  } else {
    lines.push(`"%${NODE_FALLBACK_EXEC_PATH_ENV_KEY}%" %*`);
  }
  // 可执行文件必须是最后一条命令：batch 结束时的 errorlevel 就是它的退出码。
  return `${lines.join("\r\n")}\r\n`;
}

function renderWindowsEnvGuard(envKey: string): string[] {
  return [
    `if not defined ${envKey} (`,
    `  echo zcode node fallback: ${envKey} is not set 1>&2`,
    `  exit /b ${MISSING_ENV_EXIT_CODE}`,
    ")",
  ];
}

/**
 * 内容一致（POSIX 还要求可执行位齐全）时不触碰文件；否则写唯一临时文件再 rename。
 * 并发的 agent 写入的是同一份字节，rename 谁赢都正确。
 */
export async function ensureNodeFallbackShimDir(
  binDir: string,
  platform: NodeJS.Platform,
): Promise<void> {
  await mkdir(binDir, { recursive: true });
  await Promise.all(renderNodeFallbackShims(platform).map((shim) => ensureShimFile(binDir, shim)));
}

async function ensureShimFile(binDir: string, shim: NodeFallbackShimFile): Promise<void> {
  const shimPath = join(binDir, shim.name);
  if (await isShimCurrent(shimPath, shim)) return;

  const temporaryPath = `${shimPath}.tmp-${process.pid}-${randomUUID()}`;
  try {
    await writeFile(temporaryPath, shim.content, {
      mode: shim.executable ? SHIM_EXECUTABLE_MODE : undefined,
    });
    // writeFile 的 mode 受 umask 影响，显式 chmod 保证可执行位。
    if (shim.executable) await chmod(temporaryPath, SHIM_EXECUTABLE_MODE);
    await rename(temporaryPath, shimPath);
  } catch (error) {
    await rm(temporaryPath, { force: true });
    throw error;
  }
}

async function isShimCurrent(shimPath: string, shim: NodeFallbackShimFile): Promise<boolean> {
  try {
    const [content, fileStat] = await Promise.all([readFile(shimPath, "utf8"), stat(shimPath)]);
    if (content !== shim.content) return false;
    return !shim.executable || (fileStat.mode & EXECUTABLE_BITS) === EXECUTABLE_BITS;
  } catch {
    return false;
  }
}

export async function resolveBundledNpmRoot(
  candidates: readonly string[],
): Promise<string | undefined> {
  for (const candidate of candidates) {
    if (
      (await isReadableFile(join(candidate, "bin", NPM_CLI_ENTRY))) &&
      (await isReadableFile(join(candidate, "bin", NPX_CLI_ENTRY)))
    ) {
      return candidate;
    }
  }
  return undefined;
}

async function isReadableFile(path: string): Promise<boolean> {
  try {
    await access(path, constants.R_OK);
    return true;
  } catch {
    return false;
  }
}

export function createMcpNodeFallbackProvider(
  options: CreateMcpNodeFallbackProviderOptions,
): McpNodeFallbackProvider {
  const platform = options.platform ?? process.platform;
  const binDir = join(options.storageRoot, NODE_FALLBACK_DIRECTORY_NAME, NODE_FALLBACK_SHIM_LAYOUT);
  let pending: Promise<McpNodeFallback | undefined> | undefined;

  const prepare = async (): Promise<McpNodeFallback | undefined> => {
    try {
      const [npmRoot] = await Promise.all([
        resolveBundledNpmRoot(options.npmRootCandidates),
        ensureNodeFallbackShimDir(binDir, platform),
      ]);
      options.logger?.info("MCP node fallback ready", {
        binDir,
        event: "mcp.node_fallback.ready",
        hasNpm: npmRoot !== undefined,
        module: "adapters.mcp.node_fallback",
      });
      return {
        binDir,
        env: {
          [NODE_FALLBACK_EXEC_PATH_ENV_KEY]: options.execPath,
          ...(npmRoot ? { [NODE_FALLBACK_NPM_ROOT_ENV_KEY]: npmRoot } : {}),
        },
      };
    } catch (error) {
      // 降级而非失败：没有 fallback 时连接照常进行，用户看到的就是原本的 spawn ENOENT。
      options.logger?.warn("MCP node fallback unavailable", {
        binDir,
        error: error instanceof Error ? error.message : String(error),
        event: "mcp.node_fallback.unavailable",
        module: "adapters.mcp.node_fallback",
      });
      return undefined;
    }
  };

  return {
    resolve: () => {
      pending ??= prepare();
      return pending;
    },
  };
}

/**
 * 在 server 自身 env 合并之后调用：shim 目录追加为 PATH 最后一项，用户自己的 node/npm/npx 按 PATH 顺序优先。
 * 已存在时不重复追加。
 */
export function applyMcpNodeFallbackEnv(
  env: Record<string, string>,
  fallback: McpNodeFallback | undefined,
  platform: NodeJS.Platform = process.platform,
): Record<string, string> {
  if (!fallback) return env;

  const pathApi = platform === "win32" ? win32 : posix;
  const pathDelimiter = platform === "win32" ? win32.delimiter : posix.delimiter;
  // POSIX 环境变量区分大小写，只认 `PATH`；Windows 不区分，所有大小写变体都是同一个变量。
  const pathKeys = Object.keys(env).filter((key) =>
    platform === "win32" ? key.toUpperCase() === PATH_ENV_KEY : key === PATH_ENV_KEY,
  );
  // 插入顺序最后的键是后合并进来的值（server 自己的 PATH 覆盖宿主 `Path` 时就是它）。
  const currentPath = (pathKeys.length > 0 ? env[pathKeys[pathKeys.length - 1]!] : undefined) ?? "";
  const entries = currentPath.split(pathDelimiter).filter(Boolean);
  const normalize = (value: string) => {
    const normalized = pathApi.normalize(value).replace(/[\\/]+$/, "");
    return platform === "win32" ? normalized.toLowerCase() : normalized;
  };
  const alreadyPresent = entries.some((entry) => normalize(entry) === normalize(fallback.binDir));
  const nextPath = alreadyPresent
    ? currentPath
    : currentPath
      ? `${currentPath}${pathDelimiter}${fallback.binDir}`
      : fallback.binDir;

  if (platform !== "win32") return { ...env, ...fallback.env, [PATH_ENV_KEY]: nextPath };

  // 根因（MR !3089 评审 CR-01）：Windows 上 MCP SDK 以 `{ PATH: process.env.PATH, ...env }` spawn，
  // 宿主常见键名是 `Path`，于是子进程 env 同时有 `PATH`（无 shim）与 `Path`（有 shim）；Node 在 win32
  // 把键排序后只保留第一个（`PATH`），shim 目录丢失，npx 包内再调用 node 就失败。这里删掉所有
  // 大小写变体，只写一个大写 `PATH`，正好覆盖 SDK 的默认键，cross-spawn 与 Node 看到同一个值。
  const withoutPathKeys = Object.fromEntries(
    Object.entries(env).filter(([key]) => key.toUpperCase() !== PATH_ENV_KEY),
  );
  return { ...withoutPathKeys, ...fallback.env, [PATH_ENV_KEY]: nextPath };
}
